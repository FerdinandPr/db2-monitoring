-- Monitoring-Benutzer fuer den Db2-Exporter berechtigen.
-- Der Benutzer (hier DB2MON) muss als OS-/LDAP-Benutzer existieren.
-- Ausfuehren als DBADM/SECADM:   db2 connect to <DB>
--                                db2 -tvf sql/grants.sql

GRANT CONNECT ON DATABASE TO USER DB2MON;

-- Variante A (empfohlen): nur die benoetigten Funktionen
GRANT EXECUTE ON FUNCTION SYSPROC.ENV_GET_INST_INFO       TO USER DB2MON;
GRANT EXECUTE ON FUNCTION SYSPROC.MON_GET_DATABASE        TO USER DB2MON;
GRANT EXECUTE ON FUNCTION SYSPROC.MON_GET_CONNECTION      TO USER DB2MON;
GRANT EXECUTE ON FUNCTION SYSPROC.MON_GET_BUFFERPOOL      TO USER DB2MON;
GRANT EXECUTE ON FUNCTION SYSPROC.MON_GET_TABLESPACE      TO USER DB2MON;
GRANT EXECUTE ON FUNCTION SYSPROC.MON_GET_TRANSACTION_LOG TO USER DB2MON;
GRANT EXECUTE ON FUNCTION SYSPROC.MON_GET_PKG_CACHE_STMT  TO USER DB2MON;
GRANT EXECUTE ON FUNCTION SYSPROC.ADMIN_GET_STORAGE_PATHS TO USER DB2MON;
GRANT EXECUTE ON FUNCTION SYSPROC.MON_GET_APPL_LOCKWAIT   TO USER DB2MON;
-- SYSCAT.TABLES (Tabellennamen bei Lock-Waits) ist standardmaessig fuer PUBLIC lesbar.

